-- По умолчанию агент автосборки ДЗ (project_homework_agent) собирает
-- ЧЕРНОВИК, не публикует и не назначает его группе — учитель должен явно
-- попросить это на странице подтверждения (чекбокс «Опубликовать сразу»).
-- Найдено при первом живом прогоне 2026-09-16: build.ts безусловно
-- публиковал и назначал, учитель не успевал проверить состав до того, как
-- ДЗ увидела группа.
alter table homework_proposals
  add column if not exists publish_immediately boolean not null default false;

comment on column homework_proposals.publish_immediately is
  'Учитель явно попросил опубликовать и назначить ДЗ сразу после сборки, не оставлять черновиком. Проставляется на странице подтверждения, читается build.ts.';
