-- 108: индексы под список библиотеки и статистику каталога книг.
--
-- Список библиотеки сортируется по (scraped_at desc nulls last, source_id).
-- Все листинговые индексы начинаются с (subject, exam_type, …), поэтому без
-- фильтра по предмету — а это вид по умолчанию — запрос читал таблицу целиком
-- (5343 страницы, ~42 МБ) и сортировал 21 тыс. строк ради первых двадцати.
-- При тёплом кеше это ~27 мс, при холодном — чтение 42 МБ с диска. С этим
-- индексом первые страницы берутся прямо в порядке сортировки: 24 страницы,
-- 0,3 мс. exam_type, subject и has_answer стоят в ключе, а не в INCLUDE, чтобы
-- фильтр по ним проверялся внутри индекса, без чтения строки из таблицы.
--
-- Индекс частичный, как и остальные листинговые: работает, только когда запрос
-- сам содержит organization_id IS NULL. Поэтому app/api/library/problems в
-- режиме «все» запрашивает только общие задачи, если у организации нет своих.
--
-- На глубоких смещениях (дальше ~170 строк) планировщик по-прежнему выбирает
-- полный проход: из-за условия RLS на роль он оценивает число подходящих
-- строк в 1%. Хуже, чем было, не становится.
create index if not exists idx_lib_prob_recent on public.library_problems
  (scraped_at desc nulls last, source_id, exam_type, subject, has_answer)
  where is_active = true and organization_id is null;

-- book_problem_stats() считает задания и ответы по всем книгам на каждое
-- открытие каталога. Индекс покрывает оба нужных поля — агрегат идёт по нему,
-- а не по таблице с текстами заданий.
create index if not exists book_problems_stats_idx on public.book_problems
  (book_id, answer_source)
  where is_active = true;
