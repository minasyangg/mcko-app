-- Журнал /teacher/notifications не различал, кому реально ушло сообщение —
-- ученику или его родителю: user_id в обоих случаях указывает на ПРОФИЛЬ
-- ученика (notifyParent пишет studentId, а не какого-то отдельного
-- "родительского" id — у родителя своей profiles-строки нет вовсе).
-- Колонка "Кому" в интерфейсе показывала одно и то же ФИО для обеих строк,
-- и по журналу нельзя было отличить "ушло ученику" от "ушло родителю"
-- (живой случай: администратор увидел одну строку "Власенко Глеб" в
-- журнале и не смог понять, дошло ли до родителя, хотя по факту дошло —
-- родитель подтвердил получение, и status='sent' без ошибки).
--
-- recipient — кому адресовано это сообщение с точки зрения текста и
-- Telegram chat_id, а не чей profiles.id стоит в user_id (он остаётся
-- ссылкой на ученика в обоих случаях — это и назначение/попытка, о которых
-- речь).
alter table notification_log add column if not exists recipient text not null default 'self'
  check (recipient in ('self', 'parent'));

comment on column notification_log.recipient is
  'Кому реально ушло сообщение: self — самому пользователю (user_id), parent — родителю ученика (user_id — профиль ученика, доставка на parent_telegram_chat_id)';
