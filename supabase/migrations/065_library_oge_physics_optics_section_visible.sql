-- Баг фильтра библиотеки: раздел «Оптика» (ОГЭ-физика) был is_canonical=false,
-- хотя 6 его дочерних тем канонические и содержат 137+ реальных задач.
-- LibraryFilter строит список разделов из topics.filter(parent_id === null),
-- а LibraryPage грузит только is_canonical=true темы — «Оптика» никогда не
-- попадала в этот массив, поэтому её канонические дети физически существовали
-- в данных, но не могли отрендериться нигде в дереве фильтра: раздел
-- отсутствовал в списке ("1. Механика", "2. ...", "3. Электродинамика",
-- "4. Ядерная физика" — без "Оптики" между 3 и 4).
-- У «Оптики» нет собственного fipicod — она заголовок раздела, а не листовой
-- элемент кодификатора, как и «Механика»/«Электродинамика» (у них fipicod
-- '1'/'3' и is_canonical=true) — поэтому корректное состояние здесь тоже
-- is_canonical=true, вне зависимости от fipicod.
--
-- Проверено на всю базу (все предметы/экзамены, любая глубина иерархии) —
-- это единственный такой случай, других скрытых непустых разделов нет.
update library_topics
set is_canonical = true
where id = 'f4967587-57f5-48fc-92af-31ca0ab4029f'
  and subject = 'Физика' and exam_type = 'ОГЭ' and name = 'Оптика';
