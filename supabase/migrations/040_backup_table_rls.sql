-- ============================================================
-- 040_backup_table_rls.sql
-- Снимок для отката из 034 не должен быть виден через PostgREST
-- ============================================================
--
-- `_backup_034_wrongly_locked` создавался как снимок для отката (034) и с тех
-- пор лежит в схеме public с ВЫКЛЮЧЕННЫМ RLS. Всё, что лежит в public, Supabase
-- отдаёт через PostgREST, а таблица без RLS читается кем угодно с публичным
-- anon-ключом — то есть содержимое снимка (id ответов и id попыток) доступно
-- анонимно. Database Linter помечает это как ERROR (rls_disabled_in_public).
--
-- Таблицу НЕ удаляем: это единственный путь отката правки баллов из 034, и
-- решение о его утилизации — не техническое. Включаем RLS без единой политики:
-- для всех пользовательских ролей таблица становится пустой, service role
-- (миграции, откат) RLS не подчиняется и видит снимок целиком.
--
-- Когда откат больше не нужен, снимок дропается вручную:
--   drop table _backup_034_wrongly_locked;

alter table if exists public._backup_034_wrongly_locked enable row level security;

comment on table public._backup_034_wrongly_locked is
  'Снимок для отката миграции 034 (ошибочно заблокированные ответы). RLS включён без политик: доступ только у service role. Дропнуть, когда откат перестанет быть нужен.';
