-- ============================================================
-- 115_auto_archive_previous_year.sql
-- Автоархив заданий прошлого учебного года
-- ============================================================
--
-- Назначения, открытые до 20 июня включительно (по Москве) прошлого учебного
-- года, уходят в архив ученика сами — при заходе в кабинет
-- (app/student/page.tsx, lib/assignments/archive.ts). Задания текущего
-- учебного года по-прежнему убирает только сам ученик и только через
-- archive_after_days (113, 114). Исключение — назначение, в котором ученик
-- работал уже в текущем учебном году: его автоархив не трогает, иначе начатая
-- попытка сдалась бы принудительно.
--
-- unarchived_at — память о возврате из архива (учеником или «Открыть» у
-- учителя). Возвращённое в этом учебном году автоархив не убирает повторно —
-- только после следующего 20 июня.

alter table student_final_results
  add column if not exists unarchived_at timestamptz;

comment on column student_final_results.unarchived_at is
  'Когда назначение последний раз возвращали из архива (ученик или «Открыть» у учителя). Автоархив прошлого учебного года (115) не убирает его повторно, пока unarchived_at позже начала текущего учебного года (21 июня по Москве).';

comment on column student_final_results.archived_at is
  'Назначение в архиве ученика: убрано им самим (113) или автоматически как задание прошлого учебного года (115). Пока не NULL, назначение закрыто для ученика: closed_reason = archived, если не закрыто по другой причине. Снимается возвратом из архива учеником или «Открыть» у учителя.';
