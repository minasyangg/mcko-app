-- 042_doska_board_subject.sql
-- У доски появляется предмет. Аддитивно: одна необязательная колонка,
-- существующие строки остаются валидными, политики не меняются.
--
-- Зачем. Учитель ведёт с одним учеником несколько предметов, и досок у пары
-- столько же. По одному названию их не различить — в кабинете ученика висел
-- бы список одинаковых «Иванов Пётр». Предмет и есть то, что отличает.
--
-- Почему text, а не ссылка на справочник. В mcko-app предмет везде — обычная
-- строка (tests.subject, roadmaps.subject, library_problems.subject).
-- Заводить справочник ради досок значило бы создать второй способ называть
-- предмет и рассинхронизировать его с остальным приложением.
--
-- Почему nullable. Доски, заведённые до этой миграции, предмета не имеют, и
-- придумывать им его нечестно. Интерфейс просит предмет при создании новой.
-- ============================================================

alter table doska_boards
  add column if not exists subject text
    check (subject is null or char_length(subject) between 1 and 60);

comment on column doska_boards.subject is
  'Предмет занятия, свободная строка в тех же значениях, что tests.subject. '
  'NULL — доска заведена до 042 либо предмет не указан.';

-- Кабинет ученика показывает его доски сгруппированными по предмету, а
-- учитель фильтрует свой список. И то и другое читает по владельцу/участнику,
-- индексы под которые уже есть в 041; отдельный индекс по subject не нужен —
-- досок у человека десятки, а не миллионы.
