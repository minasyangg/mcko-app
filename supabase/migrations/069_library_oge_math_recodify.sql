-- Аудит библиотеки задач ОГЭ-математика по тому же принципу, что и физика
-- (миграции 063-068): сверка с официальным кодификатором ФИПИ-2026,
-- слияние скрытых дублей, добавление отсутствующих официальных тем.
--
-- Правило разбалловки ("МАТ - ОГЭ - Первичные баллы", scoring_rules) сверено
-- со спецификацией КИМ ОГЭ 2026 по математике поштучно (задания 1-19 = 1
-- балл, 20-25 = 2 балла, максимум 31) — совпадает 1-в-1, правкам не
-- подвергалось.
--
-- Официальный кодификатор ОГЭ-математика 2026 крайне компактный: 8 разделов
-- верхнего уровня (Числа и вычисления / Алгебраические выражения / Уравнения
-- и неравенства / Последовательности / Функции / Координаты / Геометрия /
-- Статистика и теория вероятностей), от 1 до 6 листовых элементов в каждом.
-- Все 8 разделов и их номера/названия в базе уже точно совпадают с
-- официальными — расхождения только в листовых подтемах:
--
--  1) Дубль: "8.2 Вероятность" (1406 задач) и "8.3 Ве­ро­ят­ность" (6 задач,
--     другой источник парсинга — характерные мягкие переносы в написании) —
--     одна и та же официальная тема. Сливаем в 8.2 (больше задач).
--  2) Освободившийся код 8.3 официально принадлежит "Комбинаторике" —
--     отдельной теме, которой в библиотеке нет вообще (создаём пустой).
--  3) "3.4 Описание различных зависимостей с помощью функций" (10 задач) —
--     такого пункта нет в официальном разделе 3 "Уравнения и неравенства"
--     (там только 3.1-3.3); по смыслу это часть раздела 5 "Функции" —
--     переносим (parent_id + fipicod) на свободный код 5.4.
--  4) "7.7 Решение практических задач по геометрии" (457 задач) — код,
--     которого нет в официальном кодификаторе (там максимум 7.6 «Векторы на
--     плоскости», не содержательно совпадающий с этой темой) — оставляем
--     как дополнительную учебную тему сверх кодификатора, официальный 7.6
--     добавляем отдельно пустым.
--  5) Семь официальных тем в библиотеке отсутствуют полностью (0 задач под
--     любым кодом) — создаём пустыми, наполнение библиотеки отдельным
--     этапом: 1.1, 6.2, 7.6, 8.1, 8.4, 8.5 (и 8.3 после освобождения из п.2).
--
-- sort_order у всех подтем математики уже был 0 (в отличие от физики, где
-- сортировка шла по числовому sort_order=1000+n) — реальный порядок в
-- LibraryFilter.tsx/API держится на строковой сортировке fipicod, и здесь
-- коллизий вида "1.10" < "1.2" не возникает (максимум один десятичный
-- разряд), поэтому sort_order трогать не нужно.

begin;

-- ── Слияние дубля: "8.2 Вероятность" (основная) ← "8.3 Ве­ро­ят­ность" ───
update library_problems set canonical_topic_id = (
  select id from library_topics where subject='Математика' and exam_type='ОГЭ' and fipicod='8.2'
) where canonical_topic_id = (
  select id from library_topics where subject='Математика' and exam_type='ОГЭ' and fipicod='8.3' and name='Ве­ро­ят­ность'
);
update library_topics set is_canonical = false, fipicod = null
where subject='Математика' and exam_type='ОГЭ' and fipicod='8.3' and name='Ве­ро­ят­ность';

-- ── Перенос "3.4" → "5.4" (Функции), содержательно не подходит разделу 3 ─
update library_topics
set fipicod = '5.4',
    parent_id = (select id from library_topics where subject='Математика' and exam_type='ОГЭ' and fipicod='5')
where subject='Математика' and exam_type='ОГЭ' and fipicod='3.4';

-- ── Новые пустые темы (официальные элементы содержания без единой задачи
--    в библиотеке — наполнение отдельным этапом) ─────────────────────────
insert into library_topics (exam_type, subject, grade, name, parent_id, sort_order, is_canonical, fipicod)
select 'ОГЭ', 'Математика', '9', v.name,
  (select id from library_topics where exam_type='ОГЭ' and subject='Математика' and fipicod = v.parent_fipicod and parent_id is null),
  0, true, v.fipicod
from (values
  ('1.1', '1', 'Натуральные и целые числа. Признаки делимости целых чисел'),
  ('6.2', '6', 'Декартовы координаты на плоскости'),
  ('7.6', '7', 'Векторы на плоскости'),
  ('8.1', '8', 'Описательная статистика'),
  ('8.3', '8', 'Комбинаторика'),
  ('8.4', '8', 'Множества'),
  ('8.5', '8', 'Графы')
) as v(fipicod, parent_fipicod, name)
where not exists (
  select 1 from library_topics t
  where t.exam_type='ОГЭ' and t.subject='Математика' and t.fipicod = v.fipicod
);

commit;
