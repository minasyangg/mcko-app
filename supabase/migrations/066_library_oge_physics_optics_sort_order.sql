-- «Оптика» (ОГЭ-физика) отображалась первой в списке разделов вместо
-- ожидаемого места между «3. Электродинамика» и «4. Ядерная физика»:
-- у корневых разделов sort_order идёт шагом 1000 (1000/2000/3000/4000),
-- а у «Оптики» стояло мусорное значение 3 (сортировка "раньше всех").
-- По кодификатору ФИПИ оптика формально — часть раздела «Электродинамика»,
-- но в этой библиотеке решено оставить её отдельным пунктом верхнего уровня
-- (без трёхуровневой иерархии в фильтре) — sort_order=3500 просто ставит её
-- визуально между «3.» и «4.», как логическое продолжение электродинамики.
--
-- fipicod намеренно остаётся NULL (не выдумываем код ФИПИ): у «Оптики»
-- нет официального номера в кодификаторе, а фиктивный код рисковал бы
-- запутать поиск по коду/экспорт. В UI она поэтому показывается без
-- номера-префикса — как и остальные некодифицированные темы в базе.
update library_topics
set sort_order = 3500
where id = 'f4967587-57f5-48fc-92af-31ca0ab4029f'
  and subject = 'Физика' and exam_type = 'ОГЭ' and name = 'Оптика';
