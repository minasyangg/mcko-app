-- Миграция 070 добавила notification_log.recipient с default 'self' — для
-- строк, написанных ДО того, как код начал проставлять recipient явно
-- (071/lib/notifications/send.ts), это молча пометило родительские
-- уведомления как «ушло ученику». Живой случай: единственная историческая
-- запись notifyParent (родитель Власенко Глеба, назначение ДЗ 12.09) была
-- показана в /teacher/notifications с иконкой «ребёнок», хотя фактически
-- (и подтверждено получением в Telegram) ушла только родителю.
--
-- Текст сообщения однозначно определяет получателя: notifyParent всегда
-- начинает текст с «Ученику <ФИ> ...» / «Работа ученика <ФИ> ...» (см.
-- notifyAssignmentCreated/notifyAttemptFinalized) — этого паттерна не может
-- быть в тексте notifyUsers («Вам ...» / «Ваша работа ...»). Правим только
-- строки с дефолтным (непроставленным явно) recipient='self', чтобы не
-- затронуть будущие корректные записи.
update notification_log
set recipient = 'parent'
where recipient = 'self'
  and (message like 'Ученику %' or message like '%Ученику %назначен%' or message like '%Работа ученика %проверена%');
