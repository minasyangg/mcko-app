-- «Оптика» как отдельный раздел верхнего уровня путала нумерацию (см.
-- 065/066 — до этого раздел просто чинился по видимости/порядку) —
-- пользователь попросил не держать отдельный раздел вовсе, раз у него нет
-- собственного кода ФИПИ: в кодификаторе оптика формально часть раздела
-- «Электродинамика», её темы продолжают ту же последовательность кодов
-- 3.15-3.24 сразу за 3.1-3.14 электродинамики.
--
-- LibraryFilter.tsx рисует только двухуровневую иерархию (раздел → плоский
-- список подтем), рекурсии на третий уровень нет — поэтому решение не
-- "перевесить Оптику под Электродинамику как узел со своими детьми" (это
-- потребовало бы трёхуровневого UI), а расплющить: 6 тем оптики становятся
-- обычными подтемами «Электродинамики» на той же глубине, что 3.1-3.14.
-- Узел «Оптика» после этого не нужен как раздел — снимаем is_canonical, не
-- удаляя физически (мог остаться где-то как ссылка parent_id/topic_id).

update library_topics
set parent_id = (select id from library_topics where subject='Физика' and exam_type='ОГЭ' and name='Электродинамика' and parent_id is null)
where parent_id = 'f4967587-57f5-48fc-92af-31ca0ab4029f';

update library_topics
set is_canonical = false
where id = 'f4967587-57f5-48fc-92af-31ca0ab4029f'
  and subject = 'Физика' and exam_type = 'ОГЭ' and name = 'Оптика';
