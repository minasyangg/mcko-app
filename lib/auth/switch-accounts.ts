// Быстрое переключение между двумя КОНКРЕТНЫМИ аккаунтами одного человека.
//
// Список захардкожен намеренно и не берётся ни из БД, ни из параметров
// запроса: механизм пускает в чужой аккаунт, поэтому расширить его можно
// только правкой этого файла и деплоем (требование пользователя — «не должно
// распространяться на другие аккаунты, пока я не задам их лично»).
//
// Модель безопасности АСИММЕТРИЧНА, и это главное в этом файле:
//
//   админ → учитель   — без пароля. Админ и так видит и может всё, что может
//                       учитель, поэтому новых прав переход не даёт.
//   учитель → админ   — ТОЛЬКО с паролем. Иначе пароль учителя становился бы
//                       ключом от админки: кто угодно, получив доступ к
//                       аккаунту учителя (школьный компьютер, простой пароль,
//                       сохранённая сессия), одним кликом получал бы всю
//                       организацию. Пароль остаётся границей между ролями.
//
// При добавлении новых записей сохраняйте это правило: понижение роли можно
// пускать без пароля, повышение — никогда.
export interface SwitchableAccount {
  id: string
  label: string
  role: 'admin' | 'teacher'
}

export const SWITCHABLE_ACCOUNTS: SwitchableAccount[] = [
  { id: '22222222-2222-2222-2222-222222222222', label: 'Администратор', role: 'admin' },
  { id: '33333333-3333-3333-3333-333333333333', label: 'Иванова Мария Петровна', role: 'teacher' },
]

export function findSwitchable(id: string): SwitchableAccount | undefined {
  return SWITCHABLE_ACCOUNTS.find(a => a.id === id)
}

/**
 * Можно ли перейти fromId → toId вообще (обе стороны в списке, аккаунты разные).
 * Отдельно от вопроса «нужен ли пароль» — см. requiresPassword.
 */
export function isSwitchAllowed(fromId: string, toId: string): boolean {
  if (!fromId || !toId || fromId === toId) return false
  return !!findSwitchable(fromId) && !!findSwitchable(toId)
}

/**
 * Нужен ли пароль для перехода. Без пароля пускаем только когда целевая роль
 * не выше исходной — то есть админ→учитель. Любой переход В админа требует
 * пароль, даже если исходный аккаунт тоже админский (на будущее, если в
 * списке окажется больше двух записей).
 */
export function requiresPassword(fromId: string, toId: string): boolean {
  const to = findSwitchable(toId)
  if (!to) return true
  return to.role === 'admin'
}
